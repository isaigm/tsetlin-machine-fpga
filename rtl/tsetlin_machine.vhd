library ieee;
  use ieee.std_logic_1164.all;
  use ieee.numeric_std.all;
  use work.dataset_pkg.all;   -- generated by data/gen_*.py: sizes, samples, classes, seeds, MAX_UPDATES

entity tsetlin_machine is
  port (
    clk: in std_logic;
    rst: in std_logic;
    LED: out std_logic_vector(15 downto 0)
  );
end entity;

architecture Behavioral of tsetlin_machine is
    type status_t is (UPDATE_RULES, UPDATE_IDX, WAIT_FOR_SAMPLE_R, WAIT_FOR_EVAL, WAIT_FOR_DONE, TEST, FINISHED);

    constant T: integer := 2;

    signal en_update:      std_logic_vector(N_RULES - 1 downto 0) := (others => '0');
    signal ready:          std_logic_vector(N_RULES - 1 downto 0);
    signal eval:           std_logic_vector(N_RULES - 1 downto 0);
    signal eval_r:         std_logic_vector(N_RULES - 1 downto 0);
    signal sample_idx:     integer range 0 to N_SAMPLES - 1 := 0;
    signal fire_ones:      integer range 0 to N_RULES;
    signal miss_ones:      integer range 0 to N_RULES;
    signal class_r:        std_logic;
    signal p:              unsigned(15 downto 0);
    signal p_r:            unsigned(15 downto 0) := (others => '0');   -- registered p, sent to the rules
    signal curr_status:    status_t := WAIT_FOR_SAMPLE_R;

    signal epoch:          integer range 0 to MAX_UPDATES - 1 := 0;
    signal votes0:         integer range 0 to N_RULES;
    signal votes1:         integer range 0 to N_RULES;
    signal pred:           std_logic;
    signal pred_ok:        std_logic;
    signal hits:           integer range 0 to N_TEST := 0;   -- correct predictions on the test set
    signal train_finished: std_logic := '0';

    -- p = (T - v) * 65535 / (2T) for every possible v, computed at elaboration (no multiplier, no DSP)
    type p_table_t is array (-T to T) of unsigned(15 downto 0);
    function make_p_table return p_table_t is
        variable tbl: p_table_t;
    begin
        for v in -T to T loop
            tbl(v) := to_unsigned(((T - v) * 65535) / (2 * T), 16);
        end loop;
        return tbl;
    end function;
    constant P_TABLE: p_table_t := make_p_table;

begin
    LED(7 downto 0)  <= std_logic_vector(to_unsigned(hits, 8));
    LED(14 downto 8) <= (others => '0');
    LED(15)          <= '1' when curr_status = FINISHED else '0';

    pred    <= '0' when votes0 > votes1 else '1';
    pred_ok <= '1' when pred = class_r else '0';

    process(clk)
    begin
        if rising_edge(clk) then
            if rst = '1' then
                sample_idx     <= 0;
                epoch          <= 0;
                hits           <= 0;
                train_finished <= '0';
                class_r        <= CLASSES(0);
                eval_r         <= eval;
                curr_status    <= WAIT_FOR_SAMPLE_R;
            else
                en_update <= (others => '0');
                p_r       <= p;   -- valid one cycle after UPDATE_RULES, used by the rules in SELECT_NEXT_OP

                case curr_status is

                    when UPDATE_RULES =>
                        en_update   <= (others => '1');   -- all rules at once
                        curr_status <= WAIT_FOR_DONE;

                    when UPDATE_IDX =>
                        -- each pass updates all rules with one sample
                        if sample_idx = N_TRAIN - 1 then
                            sample_idx <= 0;
                            if epoch = MAX_UPDATES - 1 then
                                train_finished <= '1';
                                sample_idx     <= N_TRAIN;   -- first test sample
                            else
                                epoch <= epoch + 1;
                            end if;
                        else
                            sample_idx <= sample_idx + 1;
                        end if;

                        curr_status <= WAIT_FOR_SAMPLE_R;

                    when WAIT_FOR_SAMPLE_R =>
                        -- the rules capture the new sample in sample_r, and the top captures its class in class_r
                        class_r     <= CLASSES(sample_idx);
                        curr_status <= WAIT_FOR_EVAL;

                    when WAIT_FOR_EVAL =>
                        -- eval is computed from sample_r and captured in eval_r
                        eval_r <= eval;
                        if train_finished = '1' then
                            curr_status <= TEST;
                        else
                            curr_status <= UPDATE_RULES;
                        end if;

                    when WAIT_FOR_DONE =>
                        if ready = (ready'range => '1') then
                            curr_status <= UPDATE_IDX;
                        end if;

                    when TEST =>
                        if pred_ok = '1' then
                            hits <= hits + 1;
                        end if;

                        if sample_idx = N_SAMPLES - 1 then
                            curr_status <= FINISHED;
                        else
                            sample_idx  <= sample_idx + 1;
                            curr_status <= WAIT_FOR_SAMPLE_R;
                        end if;

                    when FINISHED =>
                        null;

                    when others =>
                        null;

                end case;
            end if;
        end if;
    end process;

    gen_rules: for i in 0 to N_RULES - 1 generate
        rule_inst: entity work.rule
        generic map (
            TARGET_CLASS => TARGET_CLASSES(i),
            SEED         => SEEDS(i),
            N_ATTRIBUTES => N_ATTRIBUTES
        )
        port map (
            clk       => clk,
            rst       => rst,
            class_r   => class_r,
            p         => std_logic_vector(p_r),
            en_update => en_update(i),
            sample    => SAMPLES(sample_idx),
            ready     => ready(i),
            eval      => eval(i)
        );
    end generate;

    process(fire_ones, miss_ones)
        variable vc: integer range -N_RULES to N_RULES;
    begin
        vc := fire_ones - miss_ones;

        if vc > T then
            vc := T;
        elsif vc < -T then
            vc := -T;
        end if;

        p <= P_TABLE(vc);
    end process;

    process(eval_r, class_r)
        variable f_ones: integer range 0 to N_RULES;
        variable m_ones: integer range 0 to N_RULES;
    begin
        f_ones := 0;
        m_ones := 0;

        for i in 0 to N_RULES - 1 loop
            if TARGET_CLASSES(i) = class_r then
                if eval_r(i) = '1' then
                    f_ones := f_ones + 1;
                else
                    m_ones := m_ones + 1;
                end if;
            end if;
        end loop;

        fire_ones <= f_ones;
        miss_ones <= m_ones;
    end process;

    process(eval_r)
        variable c0: integer range 0 to N_RULES;
        variable c1: integer range 0 to N_RULES;
    begin
        c0 := 0;
        c1 := 0;

        for i in 0 to N_RULES - 1 loop
            if eval_r(i) = '1' then
                if TARGET_CLASSES(i) = '0' then
                    c0 := c0 + 1;
                else
                    c1 := c1 + 1;
                end if;
            end if;
        end loop;

        votes0 <= c0;
        votes1 <= c1;
    end process;

end architecture;
